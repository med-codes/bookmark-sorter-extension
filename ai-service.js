/**
 * AI Service for Smart Bookmark Sorter
 * Powered by Google Gemini API
 */

const DEFAULT_MODEL = "gemini-3.8-flash";

/**
 * Validates the Gemini API key with a lightweight prompt
 */
export async function testApiKey(apiKey, model = DEFAULT_MODEL) {
  if (!apiKey || typeof apiKey !== "string" || !apiKey.trim()) {
    throw new Error("Please enter a valid Google Gemini API key.");
  }

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent?key=${encodeURIComponent(apiKey.trim())}`;

  const payload = {
    contents: [
      {
        parts: [{ text: "Respond only with valid JSON: {\"status\": \"ok\"}" }]
      }
    ],
    generationConfig: {
      responseMimeType: "application/json",
      temperature: 0.1
    }
  };

  const response = await fetch(endpoint, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload)
  });

  if (!response.ok) {
    const errorData = await response.json().catch(() => ({}));
    const message = errorData.error?.message || `API error (${response.status} ${response.statusText})`;
    throw new Error(message);
  }

  const data = await response.json();
  const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!text) {
    throw new Error("Received empty response from Gemini API.");
  }

  return { ok: true, model };
}

/**
 * Classifies a batch of bookmarks using Google Gemini API
 * @param {Array<{id: string, title: string, url: string}>} bookmarks
 * @param {Array<string>} standardCategories
 * @param {string} apiKey
 * @param {string} model
 * @returns {Promise<Array<{id: string, category: string, reason: string}>>}
 */
export async function classifyBookmarksBatch(bookmarks, standardCategories = [], apiKey, model = DEFAULT_MODEL) {
  if (!bookmarks || bookmarks.length === 0) return [];
  if (!apiKey) throw new Error("Google Gemini API key is missing. Please add it in settings.");

  const categoriesList = standardCategories.length > 0
    ? standardCategories.join(", ")
    : "Coding & Development, AI & Machine Learning, Tools & Productivity, Design & Creative, Finance & Crypto, News & Reading, Shopping & Deals, Social & Community, Travel & Places, Learning & Education, Entertainment & Media";

  const simplifiedBookmarks = bookmarks.map(b => ({
    id: String(b.id),
    title: (b.title || "").trim() || "Untitled",
    url: b.url || ""
  }));

  const systemInstruction = `You are an expert bookmark organizer. Your task is to analyze browser bookmarks and categorize each one into a clean, intuitive folder.

Preferred Standard Categories:
[${categoriesList}]

Rules:
1. For each bookmark, carefully check the domain, URL path, and title. Choose the closest matching category from the Preferred Standard Categories.
2. If and only if a bookmark clearly represents a distinct, substantive topic that does NOT fit well into any standard category, create a new concise folder name (2-3 words maximum, Title Cased, e.g. "Recipes & Cooking", "Gaming", "Real Estate", "Automotive").
3. Do NOT invent redundant or overly specific categories (e.g. use "Coding & Development" instead of "Python Scripts" or "JavaScript").
4. Always provide a short rationale (3-5 words) explaining why this category was selected.
5. Return a strict JSON array containing an object for each bookmark with exact keys:
   - "id": (string) matching the input bookmark id
   - "category": (string) folder name
   - "reason": (string) brief reason`;

  const userContent = `Categorize these ${simplifiedBookmarks.length} bookmarks:\n` + JSON.stringify(simplifiedBookmarks, null, 2);

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent?key=${encodeURIComponent(apiKey.trim())}`;

  const payload = {
    contents: [
      {
        role: "user",
        parts: [
          { text: systemInstruction + "\n\n" + userContent }
        ]
      }
    ],
    generationConfig: {
      responseMimeType: "application/json",
      temperature: 0.1
    }
  };

  const response = await fetch(endpoint, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload)
  });

  if (!response.ok) {
    const errorData = await response.json().catch(() => ({}));
    const message = errorData.error?.message || `Gemini API request failed (${response.status})`;
    throw new Error(message);
  }

  const data = await response.json();
  const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!rawText) {
    throw new Error("No response content generated by Gemini.");
  }

  // Parse JSON with fallback extraction in case of surrounding markers
  let parsed;
  try {
    parsed = JSON.parse(rawText);
  } catch (err) {
    const jsonMatch = rawText.match(/\[\s*\{[\s\S]*\}\s*\]/);
    if (jsonMatch) {
      parsed = JSON.parse(jsonMatch[0]);
    } else {
      throw new Error("Failed to parse AI response as JSON: " + err.message);
    }
  }

  if (!Array.isArray(parsed)) {
    if (parsed && typeof parsed === "object" && Array.isArray(parsed.bookmarks)) {
      parsed = parsed.bookmarks;
    } else {
      throw new Error("AI response was not a JSON array.");
    }
  }

  return parsed.map(item => ({
    id: String(item.id),
    category: (item.category || "Uncategorized").trim().replace(/[\/\\:*?"<>|]/g, "-"),
    reason: (item.reason || "AI categorized").trim()
  }));
}
